import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

// Release signing is read from an untracked keystore.properties so the key never enters git.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.arceusvault.keel"
    compileSdk {
        version = release(36)
    }

    defaultConfig {
        applicationId = "com.arceusvault.keel"
        // API 30 is the floor for auth-bound Keystore keys that accept biometric OR device credential.
        minSdk = 30
        targetSdk = 36
        versionCode = 4
        versionName = "1.1.0"
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            // Only for local UI testing (./gradlew -PallowScreenshots); every normal build blocks screenshots.
            buildConfigField("boolean", "ALLOW_SCREENSHOTS", (project.findProperty("allowScreenshots") != null).toString())
        }
        release {
            buildConfigField("boolean", "ALLOW_SCREENSHOTS", "false")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    // No dependency metadata blob in the APK/AAB: it is only readable by Google Play.
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

